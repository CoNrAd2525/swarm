class GematriaEngine:
    """High-level Gematria computation and filtering engine."""

    def __init__(self, *, config: Optional[PuzzleConfig] = None):
        self.config = config

    def compute(self, text: str, *, systems: Optional[Sequence[GematriaSystem]] = None) -> List[GematriaResult]:
        systems = systems or list(GematriaSystem)
        results: List[GematriaResult] = []
        for system in systems:
            func = GEMATRIA_FUNCTIONS.get(system)
            if func:
                results.append(GematriaResult(text=text, system=system, value=func(text)))
        return results

    def compute_all_systems(self, text: str) -> Dict[GematriaSystem, int]:
        return {r.system: r.value for r in self.compute(text)}

    def compute_batch(self, texts: Sequence[str], *, systems: Optional[Sequence[GematriaSystem]] = None) -> Dict[str, List[GematriaResult]]:
        return {text: self.compute(text, systems=systems) for text in texts}

    def filter_against_config(
        self, results: Sequence[GematriaResult], *, config: Optional[PuzzleConfig] = None,
    ) -> List[FilteredGematriaResult]:
        cfg = config or self.config
        if cfg is None:
            raise ValueError("No PuzzleConfig provided for filtering")
        filtered: List[FilteredGematriaResult] = []
        for result in results:
            is_excluded, excluded_by = False, None
            for excl_range in cfg.excluded_ranges:
                if excl_range.contains(result.value):
                    is_excluded, excluded_by = True, excl_range
                    break
            is_in_puzzle_range, puzzle_number = False, None
            if result.value > 0:
                for pn, (start, end) in PUZZLE_BIT_RANGES.items():
                    if start <= result.value <= end:
                        is_in_puzzle_range, puzzle_number = True, pn
                        break
            filtered.append(FilteredGematriaResult(
                original=result, is_excluded=is_excluded, excluded_by=excluded_by,
                is_in_puzzle_range=is_in_puzzle_range, puzzle_number=puzzle_number,
            ))
        return filtered

    def filter_values(self, values: Sequence[int], *, config: Optional[PuzzleConfig] = None, system: GematriaSystem = GematriaSystem.ORDINAL) -> List[int]:
        cfg = config or self.config
        if cfg is None:
            raise ValueError("No PuzzleConfig provided")
        return cfg.filter_gematria_values(values, system=system)

    def derive_candidate_keys(
        self, text: str, *, puzzle_number: int,
        systems: Optional[Sequence[GematriaSystem]] = None,
        skip_excluded: bool = True, transformations: bool = True,
    ) -> List[int]:
        if puzzle_number not in PUZZLE_BIT_RANGES:
            raise ValueError(f"Invalid puzzle number: {puzzle_number}")
        rng_start, rng_end = PUZZLE_BIT_RANGES[puzzle_number]
        rng_size = rng_end - rng_start + 1
        results = self.compute(text, systems=systems)
        cfg = self.config
        candidates: List[int] = []
        seen: Set[int] = set()

        def _add(key: int) -> None:
            if key in seen or not (rng_start <= key <= rng_end) or key <= 0 or key >= SECP256K1_ORDER:
                return
            if skip_excluded and cfg:
                for excl in cfg.excluded_ranges:
                    if excl.contains(key):
                        return
            seen.add(key)
            candidates.append(key)

        for result in results:
            val = result.value
            if rng_start <= val <= rng_end:
                _add(val)
            if transformations:
                _add(rng_start + val)
                if val > 0:
                    _add(rng_start + (val % rng_size))
                hash_input = f"{text}:{result.system.name}:{puzzle_number}".encode()
                h = hashlib.sha256(hash_input).digest()
                _add(rng_start + (int.from_bytes(h, "big") % rng_size))
                h2 = hashlib.sha256(h).digest()
                _add(rng_start + (int.from_bytes(h2, "big") % rng_size))
                try:
                    ripemd = hashlib.new("ripemd160", h).digest()
                    _add(rng_start + (int.from_bytes(ripemd, "big") % rng_size))
                except ValueError:
                    pass
        logger.info(f"Derived {len(candidates)} candidate keys from '{text}' for puzzle #{puzzle_number}")
        return sorted(candidates)

    def gematria_to_search_ranges(
        self, text: str, *, puzzle_number: int, spread: int = 1000,
        systems: Optional[Sequence[GematriaSystem]] = None,
    ) -> List[ExcludedRange]:
        if puzzle_number not in PUZZLE_BIT_RANGES:
            raise ValueError(f"Invalid puzzle number: {puzzle_number}")
        rng_start, rng_end = PUZZLE_BIT_RANGES[puzzle_number]
        search_ranges: List[ExcludedRange] = []
        for result in self.compute(text, systems=systems):
            center = result.value
            if center < rng_start:
                center = rng_start + (center % (rng_end - rng_start + 1))
            search_ranges.append(ExcludedRange(
                max(rng_start, center - spread), min(rng_end, center + spread),
                f"gematria-{result.system.name}-{result.text[:20]}",
            ))
        return search_ranges


