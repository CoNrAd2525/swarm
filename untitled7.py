def verify_private_key(private_key: int, expected_address: str) -> bool:
    """Verify that a private key matches an expected Bitcoin address."""
    try:
        import ecdsa
        from ecdsa import SECP256k1, SigningKey
        sk = SigningKey.from_string(private_key.to_bytes(32, "big"), curve=SECP256k1)
        vk = sk.get_verifying_key()
        pub_key = b"\x04" + vk.to_string()
        sha256_hash = hashlib.sha256(pub_key).digest()
        ripemd160 = hashlib.new("ripemd160", sha256_hash).digest()
        versioned = b"\x00" + ripemd160
        checksum = hashlib.sha256(hashlib.sha256(versioned).digest()).digest()[:4]
        import base58
        address = base58.b58encode(versioned + checksum).decode()
        match = address == expected_address
        if match:
            logger.critical(f"🔑 VERIFIED! Private key 0x{private_key:x} → {address}")
        else:
            logger.info(f"Key 0x{private_key:x} generates {address}, expected {expected_address}")
        return match
    except ImportError:
        logger.warning("ecdsa/base58 not installed. pip install ecdsa base58")
        return False


