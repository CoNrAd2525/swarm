@dataclass
class SearchCheckpoint:
    """Checkpoint for resumable search sessions."""
    puzzle_number: int
    current_position: int
    total_scanned: int
    batch_size: int
    timestamp: float
    elapsed_seconds: float
    keys_per_second: float = 0.0

    @property
    def current_position_hex(self) -> str:
        return f"0x{self.current_position:x}"

    def to_dict(self) -> Dict[str, Any]:
        return {
            "puzzle_number": self.puzzle_number,
            "current_position_hex": self.current_position_hex,
            "current_position_dec": self.current_position,
            "total_scanned": self.total_scanned,
            "batch_size": self.batch_size,
            "timestamp": self.timestamp,
            "elapsed_seconds": round(self.elapsed_seconds, 2),
            "keys_per_second": round(self.keys_per_second, 2),
        }

    def save(self, path: Union[str, Path]) -> None:
        p = Path(path)
        p.parent.mkdir(parents=True, exist_ok=True)
        with open(p, "w") as f:
            json.dump(self.to_dict(), f, indent=2)
        logger.info(f"Checkpoint saved: {self.current_position_hex} ({self.total_scanned:,} keys)")

    @classmethod
    def load(cls, path: Union[str, Path]) -> "SearchCheckpoint":
        with open(path) as f:
            data = json.load(f)
        return cls(
            puzzle_number=data["puzzle_number"],
            current_position=data["current_position_dec"],
            total_scanned=data["total_scanned"],
            batch_size=data["batch_size"],
            timestamp=data["timestamp"],
            elapsed_seconds=data["elapsed_seconds"],
            keys_per_second=data.get("keys_per_second", 0.0),
        )


class ProgressTracker:
    """Track and display search progress in Colab."""

    def __init__(self, total_keys: int, puzzle_number: int, update_interval: float = 5.0):
        self.total_keys = total_keys
        self.puzzle_number = puzzle_number
        self.update_interval = update_interval
        self.scanned = 0
        self.start_time = time.time()
        self.last_update = self.start_time
        self._checkpoints: List[SearchCheckpoint] = []

    @property
    def elapsed(self) -> float:
        return time.time() - self.start_time

    @property
    def keys_per_second(self) -> float:
        return self.scanned / self.elapsed if self.elapsed > 0.001 else 0.0

    @property
    def progress_pct(self) -> float:
        return (self.scanned / self.total_keys) * 100.0 if self.total_keys else 0.0

    @property
    def eta_seconds(self) -> float:
        kps = self.keys_per_second
        return (self.total_keys - self.scanned) / kps if kps > 0.001 else float("inf")

    def update(self, batch_size: int, current_position: int) -> None:
        self.scanned += batch_size
        now = time.time()
        if now - self.last_update >= self.update_interval:
            self._display(current_position)
            self.last_update = now
            if self._checkpoints and now - self._checkpoints[-1].timestamp >= 60:
                self._checkpoints.append(SearchCheckpoint(
                    self.puzzle_number, current_position, self.scanned,
                    batch_size, now, self.elapsed, self.keys_per_second,
                ))

    def _display(self, current_position: int) -> None:
        bar_width = 40
        filled = int(bar_width * self.progress_pct / 100)
        bar = "█" * filled + "░" * (bar_width - filled)
        eta = self.eta_seconds
        eta_str = f"{eta/3600:.1f}h" if eta > 3600 else f"{eta/60:.1f}m" if eta > 60 else f"{eta:.0f}s"
        logger.info(
            f"Puzzle #{self.puzzle_number} │{bar}│ {self.progress_pct:.4f}% │ "
            f"{self.scanned:,}/{self.total_keys:,} │ {self.keys_per_second:,.0f} keys/s │ "
            f"ETA: {eta_str} │ Pos: 0x{current_position:x}"
        )

    def final_report(self) -> str:
        return (
            f"\n{'='*60}\n  SEARCH COMPLETE — Puzzle #{self.puzzle_number}\n{'='*60}\n"
            f"  Total Scanned    : {self.scanned:,} keys\n"
            f"  Elapsed Time     : {self.elapsed:.2f}s\n"
            f"  Average Speed    : {self.keys_per_second:,.2f} keys/s\n"
            f"  Coverage         : {self.progress_pct:.6f}%\n{'='*60}"
        )


