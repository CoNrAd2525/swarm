@dataclass(frozen=True, slots=True)
class ExcludedRange:
    """An already-searched or solved key range to skip."""
    start: int
    end: int
    label: str = ""

    @property
    def start_hex(self) -> str:
        return f"0x{self.start:x}"

    @property
    def end_hex(self) -> str:
        return f"0x{self.end:x}"

    @property
    def size(self) -> int:
        return max(0, self.end - self.start + 1)

    @property
    def bit_length(self) -> int:
        return self.end.bit_length()

    def contains(self, value: int) -> bool:
        return self.start <= value <= self.end

    def overlap_with(self, other: ExcludedRange) -> RangeOverlap:
        if self.start == other.start and self.end == other.end:
            return RangeOverlap.EXACT
        if self.start <= other.start and self.end >= other.end:
            return RangeOverlap.CONTAINED
        if self.start <= other.end and self.end >= other.start:
            return RangeOverlap.PARTIAL
        return RangeOverlap.NO_OVERLAP

    def merge(self, other: ExcludedRange) -> ExcludedRange:
        if self.overlap_with(other) == RangeOverlap.NO_OVERLAP:
            if self.end + 1 == other.start:
                return ExcludedRange(self.start, other.end, f"merged({self.label},{other.label})")
            if other.end + 1 == self.start:
                return ExcludedRange(other.start, self.end, f"merged({other.label},{self.label})")
            raise ValueError(f"Cannot merge non-adjacent ranges: {self} and {other}")
        return ExcludedRange(
            min(self.start, other.start),
            max(self.end, other.end),
            f"merged({self.label},{other.label})"
        )

    def to_dict(self) -> Dict[str, Any]:
        return {
            "start_hex": self.start_hex, "end_hex": self.end_hex,
            "start_dec": self.start, "end_dec": self.end,
            "size": self.size, "label": self.label,
        }

    def __str__(self) -> str:
        lbl = f" ({self.label})" if self.label else ""
        return f"[{self.start_hex} .. {self.end_hex}]{lbl}"


@dataclass(frozen=True, slots=True)
class PuzzleRange:
    """A searchable key range for a specific puzzle number."""
    puzzle_number: int
    start: int
    end: int

    @property
    def start_hex(self) -> str:
        return f"0x{self.start:x}"

    @property
    def end_hex(self) -> str:
        return f"0x{self.end:x}"

    @property
    def total_keys(self) -> int:
        return max(0, self.end - self.start + 1)

    @property
    def bit_length(self) -> int:
        return self.puzzle_number

    @property
    def status(self) -> PuzzleStatus:
        if self.puzzle_number in SOLVED_PUZZLES:
            return PuzzleStatus.SOLVED
        if self.puzzle_number in ACTIVE_PUZZLES:
            return PuzzleStatus.ACTIVE
        if 1 <= self.puzzle_number <= 160:
            return PuzzleStatus.UNSOLVED
        return PuzzleStatus.UNKNOWN

    def batch_iterator(self, batch_size: int) -> Iterator[Tuple[int, int]]:
        pos = self.start
        while pos <= self.end:
            batch_end = min(pos + batch_size - 1, self.end)
            yield (pos, batch_end)
            pos = batch_end + 1

    def total_batches(self, batch_size: int) -> int:
        if batch_size <= 0:
            return 0
        return (self.total_keys + batch_size - 1) // batch_size

    def validate(self) -> None:
        if not (1 <= self.puzzle_number <= 160):
            raise ValueError(f"Puzzle number {self.puzzle_number} outside valid range [1, 160]")
        expected_start, expected_end = PUZZLE_BIT_RANGES.get(self.puzzle_number, (0, 0))
        if self.start < expected_start:
            logger.warning(f"Puzzle {self.puzzle_number}: start {self.start_hex} below min {hex(expected_start)}")
        if self.end > expected_end:
            logger.warning(f"Puzzle {self.puzzle_number}: end {self.end_hex} exceeds max {hex(expected_end)}")
        if self.start > self.end:
            raise ValueError(f"Puzzle {self.puzzle_number}: start > end")

    def to_dict(self) -> Dict[str, Any]:
        return {
            "puzzle_number": self.puzzle_number,
            "start_hex": self.start_hex, "end_hex": self.end_hex,
            "start_dec": self.start, "end_dec": self.end,
            "total_keys": str(self.total_keys), "status": self.status.name,
        }


@dataclass
class PuzzleConfig:
    """Complete puzzle configuration loaded from XML or built programmatically."""
    puzzle_number: int
    batch_size: int
    excluded_ranges: List[ExcludedRange] = field(default_factory=list)
    author: str = ""
    source: str = ""
    extra: Dict[str, str] = field(default_factory=dict)

    @property
    def puzzle_range(self) -> PuzzleRange:
        if self.puzzle_number in PUZZLE_BIT_RANGES:
            start, end = PUZZLE_BIT_RANGES[self.puzzle_number]
            return PuzzleRange(self.puzzle_number, start, end)
        raise ValueError(f"Unknown puzzle number: {self.puzzle_number}")

    @property
    def searchable_ranges(self) -> List[ExcludedRange]:
        """Compute the searchable key ranges (puzzle range minus excluded)."""
        puzzle = self.puzzle_range
        overlapping = sorted(
            [r for r in self.excluded_ranges if r.end >= puzzle.start and r.start <= puzzle.end],
            key=lambda r: r.start,
        )
        merged: List[ExcludedRange] = []
        for r in overlapping:
            if merged and merged[-1].end + 1 >= r.start:
                merged[-1] = merged[-1].merge(r)
            else:
                merged.append(r)
        searchable: List[ExcludedRange] = []
        cursor = puzzle.start
        for excl in merged:
            if cursor < excl.start:
                searchable.append(ExcludedRange(cursor, excl.start - 1, f"searchable-gap-{len(searchable)+1}"))
            cursor = max(cursor, excl.end + 1)
        if cursor <= puzzle.end:
            searchable.append(ExcludedRange(cursor, puzzle.end, f"searchable-gap-{len(searchable)+1}"))
        return searchable

    @property
    def total_searchable_keys(self) -> int:
        return sum(r.size for r in self.searchable_ranges)

    @property
    def total_excluded_keys(self) -> int:
        return sum(r.size for r in self.excluded_ranges)

    @property
    def coverage_pct(self) -> float:
        total = self.puzzle_range.total_keys
        return (self.total_excluded_keys / total) * 100.0 if total else 0.0

    @property
    def search_efficiency(self) -> float:
        return 100.0 - self.coverage_pct

    def validate(self) -> List[str]:
        warnings: List[str] = []
        if not (1 <= self.puzzle_number <= 160):
            warnings.append(f"Puzzle number {self.puzzle_number} is outside [1, 160]")
        if self.batch_size < 1:
            warnings.append(f"Batch size {self.batch_size} must be >= 1")
        elif self.batch_size > 10_000_000:
            warnings.append(f"Batch size {self.batch_size} is very large; may cause memory issues")
        puzzle = self.puzzle_range
        for i, excl in enumerate(self.excluded_ranges):
            if excl.start > excl.end:
                warnings.append(f"Excluded range #{i} has start > end: {excl}")
            if excl.end > puzzle.end:
                warnings.append(f"Excluded range #{i} extends beyond puzzle range: {excl}")
        sorted_ranges = sorted(self.excluded_ranges, key=lambda r: r.start)
        for i in range(len(sorted_ranges) - 1):
            if sorted_ranges[i].overlap_with(sorted_ranges[i + 1]) != RangeOverlap.NO_OVERLAP:
                warnings.append(f"Overlapping excluded ranges: {sorted_ranges[i]} and {sorted_ranges[i + 1]}")
        if self.puzzle_number in SOLVED_PUZZLES:
            warnings.append(f"Puzzle {self.puzzle_number} is already SOLVED!")
        return warnings

    def filter_gematria_values(
        self, values: Sequence[int], *, system: GematriaSystem = GematriaSystem.ORDINAL,
        also_exclude_searched: bool = False,
    ) -> List[int]:
        valid: List[int] = []
        for v in values:
            if any(r.contains(v) for r in self.excluded_ranges):
                logger.debug(f"Gematria({system.name}) value {v} (0x{v:x}): EXCLUDED")
                continue
            if also_exclude_searched:
                if any(r.contains(v) for r in self.searchable_ranges):
                    valid.append(v)
            else:
                valid.append(v)
        return valid

    def search_batches(self, batch_size: Optional[int] = None) -> Iterator[Tuple[int, int, ExcludedRange]]:
        bs = batch_size or self.batch_size
        for search_range in self.searchable_ranges:
            pos = search_range.start
            while pos <= search_range.end:
                batch_end = min(pos + bs - 1, search_range.end)
                yield (pos, batch_end, search_range)
                pos = batch_end + 1

    def total_search_batches(self, batch_size: Optional[int] = None) -> int:
        bs = batch_size or self.batch_size
        if bs <= 0:
            return 0
        return sum((r.size + bs - 1) // bs for r in self.searchable_ranges)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "puzzle_number": self.puzzle_number,
            "batch_size": self.batch_size,
            "excluded_ranges": [r.to_dict() for r in self.excluded_ranges],
            "searchable_ranges": [r.to_dict() for r in self.searchable_ranges],
            "total_searchable_keys": str(self.total_searchable_keys),
            "total_excluded_keys": str(self.total_excluded_keys),
            "coverage_pct": f"{self.coverage_pct:.4f}",
            "search_efficiency": f"{self.search_efficiency:.4f}",
            "author": self.author, "source": self.source, "extra": self.extra,
        }

    def to_json(self, indent: int = 2) -> str:
        return json.dumps(self.to_dict(), indent=indent, default=str)

    def summary(self) -> str:
        puzzle = self.puzzle_range
        lines = [
            "=" * 64,
            f"  BITCOIN PUZZLE CONFIGURATION — Puzzle #{self.puzzle_number}",
            "=" * 64,
            f"  Puzzle Status   : {puzzle.status.name}",
            f"  Key Range       : {puzzle.start_hex} → {puzzle.end_hex}",
            f"  Bit Length      : {puzzle.bit_length}",
            f"  Total Keys      : {puzzle.total_keys:.4e}",
            f"  Batch Size      : {self.batch_size:,}",
            f"  Total Batches   : {self.total_search_batches():,}",
            "-" * 64,
            f"  Excluded Ranges : {len(self.excluded_ranges)}",
            f"  Excluded Keys   : {self.total_excluded_keys:.4e}",
            f"  Searchable Keys : {self.total_searchable_keys:.4e}",
            f"  Coverage        : {self.coverage_pct:.2f}% excluded",
            f"  Efficiency      : {self.search_efficiency:.2f}% searchable",
            "-" * 64,
        ]
        if self.excluded_ranges:
            lines.append("  EXCLUDED RANGES:")
            for i, r in enumerate(self.excluded_ranges):
                lines.append(f"    #{i+1}: {r.start_hex} → {r.end_hex}  ({r.size:,} keys){'  [' + r.label + ']' if r.label else ''}")
        if self.searchable_ranges:
            lines.append("  SEARCHABLE RANGES:")
            for i, r in enumerate(self.searchable_ranges):
                lines.append(f"    #{i+1}: {r.start_hex} → {r.end_hex}  ({r.size:,} keys){'  [' + r.label + ']' if r.label else ''}")
        if self.author:
            lines.append(f"  Author          : {self.author}")
        if self.source:
            lines.append(f"  Source          : {self.source}")
        lines.append("=" * 64)
        return "\n".join(lines)


