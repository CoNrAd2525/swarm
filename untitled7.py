def generate_search_commands(
    config: PuzzleConfig, *, tools: Sequence[str] = ("keyhunt",),
    binary_paths: Optional[Dict[str, str]] = None,
) -> List[SearchCommand]:
    paths = binary_paths or {}
    commands: List[SearchCommand] = []
    generators = {
        "keyhunt": lambda sr: generate_keyhunt_command(config.puzzle_number, sr.start, sr.end, binary_path=paths.get("keyhunt", "/content/keyhunt/keyhunt")),
        "bitcrack": lambda sr: generate_bitcrack_command(config.puzzle_number, sr.start, sr.end, binary_path=paths.get("bitcrack", "/content/BitCrack/bin/cuBitCrack")),
        "collider": lambda sr: generate_collider_command(config.puzzle_number, sr.start, sr.end, binary_path=paths.get("collider", "./theCollider")),
    }
    for search_range in config.searchable_ranges:
        for tool in tools:
            gen = generators.get(tool)
            if gen:
                commands.append(gen(search_range))
            else:
                logger.warning(f"Unknown search tool: {tool}")
    return commands


