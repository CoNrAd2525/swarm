@dataclass
class SearchSession:
    """Manages a complete search session with checkpoint/resume support."""
    config: PuzzleConfig
    pool: PoolManager
    tool: str = "keyhunt"
    checkpoint_dir: str = "/content/checkpoints"
    auto_save_interval: int = 60
    _start_time: float = 0.0
    _scanned: int = 0
    _running: bool = False
    _current_checkpoint: Optional[SearchCheckpoint] = None

    def start(self) -> None:
        self._start_time = time.time()
        self._running = True
        logger.info(f"Search session started for Puzzle #{self.config.puzzle_number} using {self.tool}")
        cp_path = Path(self.checkpoint_dir) / f"puzzle_{self.config.puzzle_number}.json"
        if cp_path.exists():
            try:
                self._current_checkpoint = SearchCheckpoint.load(cp_path)
                self._scanned = self._current_checkpoint.total_scanned
                logger.info(f"Resumed from checkpoint: 0x{self._current_checkpoint.current_position:x} ({self._scanned:,} keys)")
            except Exception as e:
                logger.warning(f"Failed to load checkpoint: {e}")
        assignment = self.pool.get_assignment(self.config.puzzle_number)
        if assignment:
            logger.info(f"Range assigned: {assignment.start_hex} → {assignment.end_hex}")
        for cmd in generate_search_commands(self.config, tools=[self.tool]):
            logger.info(f"Command: {cmd.command}")

    def stop(self) -> None:
        self._running = False
        if self._current_checkpoint:
            self._current_checkpoint.save(Path(self.checkpoint_dir) / f"puzzle_{self.config.puzzle_number}.json")
        elapsed = time.time() - self._start_time
        logger.info(f"Search session stopped after {elapsed:.1f}s ({self._scanned:,} keys scanned)")

    @property
    def is_running(self) -> bool: return self._running
    @property
    def elapsed(self) -> float: return time.time() - self._start_time if self._start_time else 0.0
    @property
    def keys_per_second(self) -> float: return self._scanned / self.elapsed if self.elapsed > 0.001 else 0.0

    def report_summary(self) -> str:
        return (
            f"\n{'='*60}\n  SEARCH SESSION SUMMARY\n{'='*60}\n"
            f"  Puzzle Number    : {self.config.puzzle_number}\n"
            f"  Tool             : {self.tool}\n"
            f"  Keys Scanned     : {self._scanned:,}\n"
            f"  Elapsed Time     : {self.elapsed:.2f}s\n"
            f"  Speed            : {self.keys_per_second:,.2f} keys/s\n"
            f"  Searchable Keys  : {self.config.total_searchable_keys:.4e}\n"
            f"  Search Efficiency: {self.config.search_efficiency:.2f}%\n{'='*60}"
        )


