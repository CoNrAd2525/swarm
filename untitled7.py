def _digital_root(n: int) -> int:
    return 0 if n == 0 else 1 + ((n - 1) % 9)


def gematria_ordinal(text: str) -> int:
    return sum((ord(c) - ord('A') + 1) if 'A' <= c <= 'Z' else (ord(c) - ord('a') + 1) if 'a' <= c <= 'z' else 0 for c in text)

def gematria_reduced(text: str) -> int:
    return _digital_root(gematria_ordinal(text))

def gematria_reverse_ordinal(text: str) -> int:
    return sum((27 - (ord(c) - ord('A') + 1)) if 'A' <= c <= 'Z' else (27 - (ord(c) - ord('a') + 1)) if 'a' <= c <= 'z' else 0 for c in text)

def gematria_english(text: str) -> int:
    total = 0
    for c in text.upper():
        if 'A' <= c <= 'Z':
            idx = ord(c) - ord('A')
            total += (idx % 9 + 1) * (10 ** (idx // 9))
    return total

def gematria_hebrew_standard(text: str) -> int:
    total = 0
    for c in text:
        if c in _HEBREW_VALUES:
            total += _HEBREW_VALUES[c]
        elif 'A' <= c <= 'Z':
            total += ord(c) - ord('A') + 1
        elif 'a' <= c <= 'z':
            total += ord(c) - ord('a') + 1
    return total

def gematria_prime(text: str) -> int:
    total = 0
    for c in text.upper():
        if 'A' <= c <= 'Z':
            idx = ord(c) - ord('A')
            if idx < len(_PRIMES_26):
                total += _PRIMES_26[idx]
    return total

