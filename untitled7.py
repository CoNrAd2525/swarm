def get_wif(priv_key_int: int) -> str:
    key_bytes = priv_key_int.to_bytes(32, 'big')
    extended = b'\x80' + key_bytes + b'\x01'
    checksum = hashlib.sha256(hashlib.sha256(extended).digest()).digest()[:4]
    return base58.b58encode(extended + checksum).decode('utf-8')

def get_address(priv_key_int: int) -> str:
    """Address generation using the fixed RIPEMD-160."""
    sk = ecdsa.SigningKey.from_string(priv_key_int.to_bytes(32, 'big'), curve=ecdsa.SECP256k1)
    vk = sk.get_verifying_key()
    prefix = b'\x02' if vk.to_string()[32] % 2 == 0 else b'\x03'
    pub_key = prefix + vk.to_string()[:32]

    sha256_hash = hashlib.sha256(pub_key).digest()

    # Use the fixed function
    ripemd160_hash = get_ripemd160_hash(sha256_hash)

    extended = b'\x00' + ripemd160_hash
    checksum = hashlib.sha256(hashlib.sha256(extended).digest()).digest()[:4]
    return base58.b58encode(extended + checksum).decode('utf-8')

