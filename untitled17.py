import hashlib
import ecdsa
import base58

TARGET_ADDRESS = "1MVDYgVaSN6iKKEsbzRUAYFhNJT1eLf2E3"

def get_private_key_wif(private_key_int: int) -> str:
    """Convert Int -> WIF Compressed"""
    key_bytes = private_key_int.to_bytes(32, 'big')
    extended = b'\x80' + key_bytes + b'\x01'
    checksum = hashlib.sha256(hashlib.sha256(extended).digest()).digest()[:4]
    final = extended + checksum
    return base58.b58encode(final).decode('utf-8')

def get_public_key_address(private_key_int: int) -> str:
    """Convert Int -> Bitcoin Address (P2PKH Compressed)"""
    sk = ecdsa.SigningKey.from_string(private_key_int.to_bytes(32, 'big'), curve=ecdsa.SECP256k1)
    vk = sk.get_verifying_key()
    # Compressed Public Key
    pub_key_bytes = b'\x02' + vk.to_string()[:32] if vk.to_string()[32] % 2 == 0 else b'\x03' + vk.to_string()[:32]

    sha256_hash = hashlib.sha256(pub_key_bytes).digest()
    ripemd160 = hashlib.new('ripemd160', sha256_hash).digest()

    # Add network byte (0x00 for Mainnet)
    extended = b'\x00' + ripemd160

    # Checksum
    checksum = hashlib.sha256(hashlib.sha256(extended).digest()).digest()[:4]
    final = extended + checksum

    return base58.b58encode(final).decode('utf-8')

